// 고를 수 있는 부서 목록. value가 번호표에 적히는 부서명입니다.
//   본청: "연구정책과 (연구정책국)"  ·  소속기관: "기획조정과 (농과원)" / "토양물환경과 (농과원 농업환경부)"
const CHO = 'ㄱㄲㄴㄷㄸㄹㅁㅂㅃㅅㅆㅇㅈㅉㅊㅋㅌㅍㅎ';
export const ORGS = [];
for (const [inst, short, units] of ORG_TREE) {
  // 1단계 자체(예: 연구정책국, 농업환경부)도 고를 수 있게
  if (inst === '본청') for (const up of Object.keys(units)) if (up !== '직속') ORGS.push(mk(inst, short, '', up));
  for (const [up, list] of Object.entries(units)) {
    if (up !== '직속' && inst !== '본청') ORGS.push(mk(inst, short, '', up));
    for (const name of list) ORGS.push(mk(inst, short, up === '직속' ? '' : up, name));
  }
}
function mk(inst, short, up, name) {
  const where = inst === '본청' ? (up || '본청') : (up ? `${short} ${up}` : short);
  const value = `${name} (${where})`;
  return { inst, short, up, name, value, key: norm(`${name} ${up} ${inst} ${short}`), cho: cho(`${name}${up}${short}`) };
}

// ---------- 검색(자동완성) ----------
function norm(s) { return String(s || '').replace(/\s+/g, '').toLowerCase(); }
function cho(s) {
  let o = '';
  for (const ch of String(s).replace(/\s+/g, '')) {
    const c = ch.charCodeAt(0) - 0xac00;
    o += c >= 0 && c < 11172 ? CHO[Math.floor(c / 588)] : ch;
  }
  return o;
}
const isCho = s => /^[ㄱ-ㅎ]+$/.test(s);

// 입력어(띄어쓰기로 여러 단어 가능)로 부서를 찾습니다. 예: "연구정", "농과원 토양", "ㅇㄱㅈㅊ"
export function searchOrgs(q, limit = 8) {
  const words = String(q || '').trim().split(/\s+/).filter(Boolean);
  if (!words.length) return [];
  const out = [];
  for (const o of ORGS) {
    let score = 0, ok = true;
    for (const w of words) {
      const nw = norm(w);
      if (isCho(nw)) { const i = o.cho.indexOf(nw); if (i < 0) { ok = false; break; } score += i === 0 ? 3 : 1; continue; }
      const i = o.key.indexOf(nw);
      if (i < 0) { ok = false; break; }
      score += norm(o.name).startsWith(nw) ? 5 : (i < norm(o.name).length ? 3 : 1);
    }
    if (ok) out.push({ o, score: score - o.value.length / 100 });
  }
  return out.sort((a, b) => b.score - a.score).slice(0, limit).map(x => x.o);
}
export const isKnownOrg = v => ORGS.some(o => o.value === v);
